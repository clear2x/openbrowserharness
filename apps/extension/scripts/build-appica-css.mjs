/**
 * Build the SidePanel's Appica CSS artifact:
 *
 *   scripts/build-appica-css.mjs
 *     → writes src/sidepanel-dsh/appica.input.css (Tailwind v4 source, derived)
 *     → runs @tailwindcss/cli → src/sidepanel-dsh/appica.generated.css
 *
 * Why derived: `@appica/ui-react/styles.css` is a Tailwind SOURCE file whose
 * first line `@import 'tailwindcss'` pulls in the full preflight + base layer.
 * The SidePanel injects its own design system on the same document, so a
 * global reset would restyle the whole shell. This script therefore assembles
 * the input from the package's source file with three adjustments:
 *
 * 1. drop `@import 'tailwindcss'` — replaced by the theme + utilities layers
 *    only (no preflight, no base);
 * 2. drop the `@layer base` block (`* { border-border }`, `body { … }`) —
 *    the document-wide pollution;
 * 3. extend the `dark` variant and the dark token selector with the shell's
 *    own dark marker (`body[data-ds-dark-theme]`, extension-shell's
 *    ThemePresenter), so Appica components follow the shell theme with no
 *     JS-side class bridging.
 *
 * Re-run after bumping @appica/ui-react; the generated artifact is committed.
 * @module build-appica-css
 */

import { execFileSync } from 'node:child_process'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { readFileSync, realpathSync, writeFileSync } from 'node:fs'

const here = dirname(fileURLToPath(import.meta.url))
const pkgRoot = dirname(here)
const srcRoot = join(pkgRoot, 'src', 'sidepanel-dsh')
const appicaStyles = join(pkgRoot, 'node_modules', '@appica/ui-react', 'styles.css')
const inputPath = join(srcRoot, 'appica.input.css')
const outputPath = join(srcRoot, 'appica.generated.css')

const source = readFileSync(appicaStyles, 'utf8')
const lines = source.split('\n')

/** Slice the half-open [startMarker, endMarker) line range by prefix match. */
function section(startPrefix, endExclusivePrefixes) {
  const start = lines.findIndex(line => line.startsWith(startPrefix))
  if (start === -1) throw new Error(`appica styles: section not found: ${startPrefix}`)
  let end = lines.length
  for (let i = start + 1; i < lines.length; i += 1) {
    if (endExclusivePrefixes.some(prefix => lines[i].startsWith(prefix))) {
      end = i
      break
    }
  }
  return lines.slice(start, end).join('\n')
}

const darkVariant = '@custom-variant dark (&:is(.dark *, [data-ds-dark-theme] *));'
const motionReduce = section('@custom-variant motion-reduce', ['@custom-variant', '@theme'])
const motionSafe = section('@custom-variant motion-safe', ['@custom-variant', '@theme'])
const hoverNone = section('@custom-variant hover-none', ['@theme'])
const themeBlock = section('@theme inline {', [':root,'])
const lightTokens = section(':root,', ['.dark {'])
// The dark token block keeps its own leading line so the appended shell
// selector reads as one group: `.dark, [data-ds-dark-theme] { … }`.
const darkTokensRaw = section('.dark {', ['@layer base {'])
const darkTokens = darkTokensRaw.replace(/^\.dark \{$/m, '.dark,\n[data-ds-dark-theme] {')
// Custom utilities/keyframes after the base layer — referenced by name only
// when a component uses them, so carrying them whole is harmless.
const utilitiesTail = lines.slice(lines.findIndex(line => line.startsWith('@utility animate-ping-paced'))).join('\n')

const input = `/* Generated by scripts/build-appica-css.mjs — edit that script, not this file.
 * Source: @appica/ui-react/styles.css minus preflight/base (see the script header). */

@import 'tailwindcss/theme.css' layer(theme);
@import 'tailwindcss/utilities.css' layer(utilities);

/* realpath: pnpm installs the package as a symlink, and the Tailwind source
 * scan does not follow it — the @source must name the real directory. */
@source '${realpathSync(join(pkgRoot, 'node_modules', '@appica', 'ui-react'))}';
@source '../src/sidepanel-dsh/user-plugin-panel.tsx';

${darkVariant}
${motionReduce}
${motionSafe}
${hoverNone}

${themeBlock}

${lightTokens}

${darkTokens}

${utilitiesTail}
`

writeFileSync(inputPath, input)

execFileSync('./node_modules/.bin/tailwindcss', [
  '-i', inputPath,
  '-o', outputPath,
  '--minify',
], { cwd: pkgRoot, stdio: 'inherit' })
